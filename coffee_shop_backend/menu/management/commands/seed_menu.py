class Command(BaseCommand):
    help = 'Seed cafe categories and products.'

    def handle(self, *args, **options):
        category_map = {}
        for item in CATEGORIES:
            category, _ = Category.objects.update_or_create(
                slug=item['slug'],
                defaults={
                    'name': item['name'],
                    'image_url': item['image_url'],
                    'is_active': True,
                }
            )
            category_map[item['slug']] = category

        created_or_updated = 0
        for name, category_slug, description, price, image_url, temperature, caffeine, prep, calories, featured in PRODUCTS:
            category = category_map[category_slug]
            Product.objects.update_or_create(
                name=name,
                defaults={
                    'description': description,
                    'price': price,
                    'image_url': image_url,
                    'category': category,
                    'temperature': temperature,
                    'has_caffeine': caffeine,
                    'preparation_time': prep,
                    'calories': calories,
                    'is_featured': featured,
                    'is_available': True,
                    'stock': 100,
                }
            )
            created_or_updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'Seeded {len(category_map)} categories and {created_or_updated} products.'
            )
        )
